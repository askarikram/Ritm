const formatters=new Map();
function formatter(timeZone){
  if(typeof timeZone!=='string'||!timeZone||timeZone.length>100)throw Error('Некорректный часовой пояс.');
  if(!formatters.has(timeZone)){
    try{formatters.set(timeZone,new Intl.DateTimeFormat('en-CA',{timeZone,year:'numeric',month:'2-digit',day:'2-digit'}));}
    catch{throw Error('Некорректный часовой пояс.');}
  }
  return formatters.get(timeZone);
}
export function dateInZone(timeZone,now=Date.now()){
  const parts=formatter(timeZone).formatToParts(new Date(now)),value=type=>parts.find(part=>part.type===type).value;
  return value('year')+'-'+value('month')+'-'+value('day');
}
export function wishDay(timeZone,now=Date.now()){
  const date=dateInZone(timeZone,now);
  let low=now,high=now+36*60*60*1000;
  while(high-low>1000){
    const middle=Math.floor((low+high)/2);
    if(dateInZone(timeZone,middle)===date)low=middle;else high=middle;
  }
  return {date,timeZone,expiresAt:new Date(high).toISOString(),refreshAfterMs:Math.max(1000,high-now)};
}
export function wishForDay(lane,date){
  if(!Number.isInteger(lane)||lane<0||lane>=WISHES.length)throw Error('Некорректный набор пожеланий.');
  if(typeof date!=='string'||!/^\d{4}-\d{2}-\d{2}$/.test(date))throw Error('Некорректная дата.');
  const value=new Date(date+'T00:00:00Z');
  if(Number.isNaN(value.getTime())||value.toISOString().slice(0,10)!==date)throw Error('Некорректная дата.');
  const day=Math.floor(value.getTime()/86400000),index=((day%30)+30)%30;
  return WISHES[lane][index];
}
